// Campaign playbooks: how each kind of campaign is run, written down once as
// data. A playbook is the shape a senior social media manager would give a
// campaign — what each phase is for, which formats carry it, why someone would
// share it, how it opens, what the Stories do and which of the brand's own
// photos suit it.
//
// The skeleton (skeleton.ts) turns a playbook and a brief into dated pieces;
// the plan prompt and Studio read `purpose` and `rules` so a piece made in a
// phase does that phase's job.
//
// Ids are stored on campaigns and pieces: add new ones, never rename.
// Pure and browser-safe.
import type { DeliverableId } from "@/lib/studio/creative-knowledge";
import type {
  CampaignFormat,
  CampaignGoalKind,
  CampaignPace,
  MediaRole,
  ShareAimId,
  StoryThemeId,
} from "./contracts";

/** Where a phase sits: before the key date, on it, or after it. */
export type PhaseWhen = "before" | "day" | "after";

export type PlaybookPhase = {
  id: string;
  label: string;
  when: PhaseWhen;
  /** Its part of the before (or after) window, relative to its siblings. */
  share: number;
  /** What this phase must do, said to the writer. */
  purpose: string;
  aims: ShareAimId[];
  /** Preferred formats, best first. A channel that can't carry one gets the next. */
  formats: CampaignFormat[];
  deliverable: DeliverableId;
  /** Opening styles (HOOK_STYLES ids) that suit the phase. */
  hooks: string[];
  /** The Story theme for this phase, or null for no Stories. */
  story: StoryThemeId | null;
  /** Which of the person's photos or clips suit it. */
  media: MediaRole[];
  /** How hard the phase asks people to act. */
  cta: "none" | "soft" | "link";
};

export type Playbook = {
  id: string;
  label: string;
  /** One short line for the gallery card. */
  line: string;
  /** Icon name from @/components/icons (mapped in the UI). */
  icon: string;
  group: "launch" | "sell" | "grow" | "people" | "moment";
  defaultWeeks: number;
  /** Days after the key date the follow-up runs. */
  afterDays: number;
  pace: CampaignPace;
  goal: CampaignGoalKind;
  needs: { keyDate: boolean; link: boolean; product: boolean; media: boolean };
  phases: PlaybookPhase[];
  /** Rules every piece of this campaign follows. */
  rules: string[];
};

