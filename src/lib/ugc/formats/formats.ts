// Creator video formats: the kinds of Reels that really travel (street
// interviews, skits, car talks, GRWM...), written as data. Pure and
// browser-safe.
//
// Each format is a director's brief the code turns into the video prompt
// (`buildFormatVideoPrompt`) and the script writer follows (`formatBrief`):
// who holds the phone, the light, the place, the cast, the beats and their
// cuts, the sound, and how the product shows up without the video becoming an
// ad. Places and twists are rotated per brand (`pickVariant`), so two videos
// of the same format never match.
//
// Ids are stored on briefs, scripts and renders: add formats, never rename or
// remove one. Old brief formats resolve through `LEGACY_FORMAT_ALIASES`.

import type {
  BeatCut,
  BeatRole,
  FormatBeat,
  FormatPlace,
  FormatRole,
  FormatTwist,
  Speaker,
  UgcFormat,
  UgcFormatGroup,
} from "./types";

const b = (
  role: BeatRole,
  share: number,
  speaker: Speaker,
  cut: BeatCut,
  shot: string,
  action: string,
): FormatBeat => ({ role, share, speaker, cut, shot, action });
const place = (id: string, label: string, set: string, light: string): FormatPlace => ({
  id,
  label,
  set,
  light,
});
const twist = (id: string, idea: string): FormatTwist => ({ id, idea });
const role = (key: "A" | "B", title: string, position: string, behaviour: string): FormatRole => ({
  key,
  title,
  position,
  behaviour,
});

