export const UGC_FORMAT_IDS = UGC_FORMATS.map((f) => f.id) as [string, ...string[]];

/** The brief formats before the library, kept so old projects still resolve. */
export const LEGACY_FORMAT_ALIASES: Record<string, string> = {
  testimonial: "honest-review",
  problem_solution: "hot-take",
  demo: "unboxing",
  unboxing: "unboxing",
  before_after: "before-after",
  storytelling: "storytime",
  founder: "founder-story",
  review: "honest-review",
  educational: "three-reasons",
  viral_hook: "hot-take",
};

/** A library format by id, or by an old brief format's id. */
export function ugcFormat(id: string | null | undefined): UgcFormat | null {
  if (!id) return null;
  const key = LEGACY_FORMAT_ALIASES[id] ?? id;
  return UGC_FORMATS.find((f) => f.id === key) ?? null;
}

export function formatsInGroup(group: UgcFormatGroup): UgcFormat[] {
  return UGC_FORMATS.filter((f) => f.group === group);
}
