export function playbookFor(framework: string | null, paths: string[]): Playbook {
  const has = (re: RegExp) => paths.some((p) => re.test(p));
  switch (framework) {
    case "Next.js":
      return has(/^(src\/)?app\/layout\.(tsx|jsx|ts|js)$/)
        ? PLAYBOOKS["next-app"]
        : PLAYBOOKS["next-pages"];
    case "Nuxt":
      return PLAYBOOKS.nuxt;
    case "Astro":
      return PLAYBOOKS.astro;
    case "SvelteKit":
      return PLAYBOOKS.sveltekit;
    case "Remix":
      return PLAYBOOKS.remix;
    case "Gatsby":
      return PLAYBOOKS.gatsby;
    case "Vite":
    case "Vue":
    case "Create React App":
      return PLAYBOOKS["vite-spa"];
    case "Angular":
      return PLAYBOOKS.angular;
    case "Static HTML":
      return PLAYBOOKS.static;
    default:
      return PLAYBOOKS.generic;
  }
}

/** Imports a patch may add: the framework's head helpers plus packages the repository already depends on. */
export function allowedImportsFor(playbook: Playbook, dependencies: string[]): Set<string> {
  const deps = new Set(dependencies);
  const packageOf = (spec: string) =>
    spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0];
  // Virtual modules (#app, $app/…, astro:…) belong to the framework itself.
  const isVirtual = (spec: string) => /^(#|\$|astro:)/.test(spec);
  return new Set(
    playbook.allowedImports.filter((spec) => isVirtual(spec) || deps.has(packageOf(spec))),
  );
}
