// The UGC creative engine: turns product facts + Brand DNA + workspace profile
// + the brief into ad concepts (hooks, angle, scene-by-scene script, CTA,
// captions), and rewrites a script on request. Claude writes; this module
// enforces: ids and timings are normalised, dialogue is sized to the clip, and
// every specific claim is checked against the product facts — flagged claims
// get one automatic repair pass, and anything still unsupported is surfaced
// to the user as a warning rather than silently kept.
import "server-only";
import { llmText } from "@/lib/ai-gateway.server";
import { serializeBrandContext, type BrandCtxDna } from "@/lib/ai/brand-context";
import { checkScriptClaims, validFactIds, type ClaimWarning } from "@/lib/ugc/grounding";
import {
  CREATOR_VIBES,
  CTA_PRESETS,
  FORMATS,
  LANGUAGES,
  OBJECTIVES,
  TONES,
  labelOf,
  platformPreset,
} from "@/lib/ugc/options";
import { dialogueWordBudget, fitScenes, scriptWordCount } from "@/lib/ugc/prompt";
import {
  ConceptSchema,
  ScriptSchema,
  type Brief,
  type Concept,
  type Product,
  type Script,
} from "@/lib/ugc/schemas";
import { UNTRUSTED_DATA_RULE, wrapUntrusted } from "@/server/guardrails/untrusted";
import { HttpError } from "@/server/http-error";
import { log } from "@/server/observability/logger";

export type WorkspaceProfile = { industry?: string | null; audience?: string | null };

export type ConceptContext = {
  product: Product;
  brief: Brief;
  brand: Record<string, unknown>;
  workspace: WorkspaceProfile;
  durationSec: number;
  /** Brand Kit writing + video style for this project (styleBlockFor "ugc"). */
  styleText?: string;
};

export type Completer = typeof llmText;

const SCENE_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["start", "end", "shot", "action", "dialogue", "productPlacement", "caption"],
  properties: {
    start: { type: "number" },
    end: { type: "number" },
    shot: { type: "string", description: "Camera framing, e.g. 'close selfie at arm's length'." },
    action: { type: "string", description: "What the creator physically does." },
    dialogue: { type: "string", description: "Exact spoken words, or empty." },
    productPlacement: { type: "string", description: "How and where the product is visible." },
    caption: {
      type: "string",
      description: "Short on-screen caption to add in editing (not rendered).",
    },
  },
} as const;

const SCRIPT_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["hook", "scenes", "cta", "postCaption", "hashtags", "factIds"],
  properties: {
    hook: { type: "string" },
    scenes: { type: "array", items: SCENE_SCHEMA },
    cta: { type: "string" },
    postCaption: { type: "string" },
    hashtags: { type: "array", items: { type: "string" } },
    factIds: { type: "array", items: { type: "string" } },
  },
} as const;

const CONCEPTS_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["concepts"],
  properties: {
    concepts: {
      type: "array",
      items: {
        type: "object",
        additionalProperties: false,
        required: ["title", "angle", "format", "hooks", "whyItWorks", "script"],
        properties: {
          title: { type: "string" },
          angle: { type: "string" },
          format: { type: "string", enum: FORMATS.map((f) => f.id) },
          hooks: { type: "array", items: { type: "string" } },
          whyItWorks: { type: "string" },
          script: SCRIPT_SCHEMA,
        },
      },
    },
  },
} as const;

function systemPrompt(ctx: ConceptContext): string {
  const budget = dialogueWordBudget(ctx.durationSec);
  const language = labelOf(LANGUAGES, ctx.brief.language);
  return `You are a senior performance creative strategist who writes user-generated-content (UGC) video ads that convert.
${UNTRUSTED_DATA_RULE}

The ad is ONE continuous ${ctx.durationSec}-second clip generated by an AI video model: one creator, one location, filmed on a phone. Write for that:
- 2 to 4 scenes with start/end seconds covering 0–${ctx.durationSec}. Scene 1 is the hook and must grab attention within 1.5 seconds; the last scene lands the call to action.
- Spoken dialogue across ALL scenes totals at most ${budget} words, in ${language}. It must sound like a real person talking — contractions, plain words, no marketing jargon, no announcer voice.
- The product is clearly visible and demonstrated, with concrete physical actions and camera framing (shot) for each scene.
- Claims: only use the product facts provided. Every specific claim (numbers, results, timeframes, certifications, rankings, guarantees, prices, medical effects) must come from a fact; list the ids of facts you relied on in factIds. If a fact isn't provided, don't claim it. Never invent features, reviews, statistics or offers.
- Respect the brand voice and the do/don't rules in Brand DNA.
- Captions are short text the editor adds later; the video itself will contain no text.
- hooks: 3 alternative opening lines for this concept (the script's hook is the best one).
- postCaption: the social post text to publish with the video; hashtags without "#", 3–6 of them.`;
}

function userPrompt(ctx: ConceptContext, extra: string): string {
  const { product, brief } = ctx;
  const platform = platformPreset(brief.platform);
  const vibe = CREATOR_VIBES.find((v) => v.id === brief.creator.vibe)?.label ?? brief.creator.vibe;
  const brandContext = serializeBrandContext(ctx.brand as BrandCtxDna, { maxCharsPerField: 400 });
  const facts = product.facts.map((f) => ({ id: f.id, fact: f.text }));
  return `PRODUCT
${wrapUntrusted(
  "product",
  JSON.stringify(
    {
      name: product.name,
      brand: product.brand,
      category: product.category,
      price: product.price,
      description: product.description,
      facts,
      benefits: product.benefits,
      audience: product.audienceHints,
      useCases: product.useCases,
    },
    null,
    2,
  ),
  { maxChars: 8000, route: "ugc.concepts" },
)}

BRIEF
- Objective: ${labelOf(OBJECTIVES, brief.objective)}
- Platform: ${platform.label} — ${platform.native}
- Preferred format: ${labelOf(FORMATS, brief.format)}
- Tone: ${labelOf(TONES, brief.tone)}
- Language: ${labelOf(LANGUAGES, brief.language)}
- Target audience: ${brief.audience || ctx.workspace.audience || product.audienceHints.join("; ") || "infer from the product"}
- Call to action: ${brief.cta || CTA_PRESETS[brief.objective][0]}
- Creator: ${brief.creator.gender}, age ${brief.creator.age}, ${vibe}
${brief.instructions ? `- Creative notes from the marketer: ${brief.instructions}` : ""}
${ctx.workspace.industry ? `- Industry: ${ctx.workspace.industry}` : ""}

${brandContext ? wrapUntrusted("brand dna", brandContext, { maxChars: 4000, route: "ugc.concepts" }) : "No Brand DNA saved."}
${ctx.styleText ? `\nBRAND STYLE (write the dialogue, hooks and post caption in this style; facts still come only from the product facts)\n${wrapUntrusted("brand style", ctx.styleText, { maxChars: 3000, route: "ugc.concepts" })}\n` : ""}
${extra}`;
}

type RawScript = {
  hook?: string;
  scenes?: Array<Record<string, unknown>>;
  cta?: string;
  postCaption?: string;
  hashtags?: string[];
  factIds?: string[];
};

/** Normalise model output into a valid Script sized to the clip, or null. */
export function normalizeScript(raw: RawScript, ctx: ConceptContext): Script | null {
  const scenes = (Array.isArray(raw.scenes) ? raw.scenes : []).slice(0, 6).map((s, i) => ({
    id: `s${i + 1}`,
    start: Number(s.start) || 0,
    end: Number(s.end) || 0,
    shot: String(s.shot ?? "").slice(0, 300),
    action: String(s.action ?? "").slice(0, 500),
    dialogue: String(s.dialogue ?? "").slice(0, 400),
    productPlacement: String(s.productPlacement ?? "").slice(0, 300),
    caption: String(s.caption ?? "").slice(0, 120),
  }));
  if (!scenes.length) return null;
  const parsed = ScriptSchema.safeParse({
    hook: String(raw.hook ?? scenes[0].dialogue ?? "").slice(0, 200) || "Hook",
    scenes: fitScenes(
      scenes.map((s) => ({ ...s, end: s.end > s.start ? s.end : s.start + 1 })),
      ctx.durationSec,
    ),
    cta: String(raw.cta ?? ctx.brief.cta ?? "").slice(0, 120),
    postCaption: String(raw.postCaption ?? "").slice(0, 600),
    hashtags: (Array.isArray(raw.hashtags) ? raw.hashtags : [])
      .map((h) => String(h).replace(/^#/, "").replace(/\s+/g, "").slice(0, 40))
      .filter(Boolean)
      .slice(0, 10),
    factIds: validFactIds(
      Array.isArray(raw.factIds) ? raw.factIds.map(String) : [],
      ctx.product.facts,
    ),
  });
  return parsed.success ? parsed.data : null;
}

function scriptWarnings(script: Script, ctx: ConceptContext): string[] {
  const warnings = checkScriptClaims(script, ctx.product.facts).map((w: ClaimWarning) => w.message);
  const words = scriptWordCount(script, ctx.brief.language);
  const budget = dialogueWordBudget(ctx.durationSec);
  if (words > budget + 3) {
    warnings.push(
      `The dialogue is ${words} words; about ${budget} fit in ${ctx.durationSec} seconds. Trim it so the creator isn't rushed.`,
    );
  }
  return warnings;
}

async function complete(
  completer: Completer,
  ctx: ConceptContext,
  extra: string,
  schema: Record<string, unknown>,
  maxTokens: number,
): Promise<unknown> {
  const result = await completer({
    route: "ugc.concepts",
    system: systemPrompt(ctx),
    user: userPrompt(ctx, extra),
    maxTokens,
    outputSchema: schema,
    timeoutMs: 90_000,
    retries: 1,
  });
  if (result.truncated) throw new HttpError(502, "The concepts were cut off. Please try again.");
  try {
    return JSON.parse(result.text);
  } catch {
    throw new HttpError(502, "The concepts couldn't be read. Please try again.");
  }
}

type RawConcept = {
  title?: string;
  angle?: string;
  format?: string;
  hooks?: string[];
  whyItWorks?: string;
  script?: RawScript;
};

function toConcepts(raw: unknown, ctx: ConceptContext): Concept[] {
  const list = ((raw as { concepts?: RawConcept[] })?.concepts ?? []).slice(0, 4);
  const out: Concept[] = [];
  list.forEach((c, i) => {
    const script = c.script ? normalizeScript(c.script, ctx) : null;
    if (!script) return;
    const hooks = [script.hook, ...(Array.isArray(c.hooks) ? c.hooks.map(String) : [])]
      .map((h) => h.trim().slice(0, 200))
      .filter(
        (h, idx, all) => h && all.findIndex((x) => x.toLowerCase() === h.toLowerCase()) === idx,
      )
      .slice(0, 5);
    const parsed = ConceptSchema.safeParse({
      id: `c${i + 1}`,
      title: String(c.title ?? `Concept ${i + 1}`).slice(0, 120),
      angle: String(c.angle ?? "").slice(0, 400),
      format: FORMATS.some((f) => f.id === c.format) ? c.format : ctx.brief.format,
      hooks,
      whyItWorks: String(c.whyItWorks ?? "").slice(0, 400),
      script,
      warnings: scriptWarnings(script, ctx).slice(0, 10),
    });
    if (parsed.success) out.push(parsed.data);
  });
  return out;
}

export async function generateConcepts(
  ctx: ConceptContext,
  completer: Completer = llmText,
): Promise<Concept[]> {
  const raw = await complete(
    completer,
    ctx,
    `Write 3 distinct concepts. Concept 1 uses the preferred format; concepts 2 and 3 use other formats that suit this product and objective. Each has a different hook strategy.`,
    CONCEPTS_SCHEMA as unknown as Record<string, unknown>,
    8000,
  );
  let concepts = toConcepts(raw, ctx);
  if (!concepts.length) throw new HttpError(502, "No usable concepts came back. Please try again.");

  const flagged = concepts.filter((c) => c.warnings.length);
  if (flagged.length) {
    log.info("ugc.concepts.repair", { flagged: flagged.length });
    const repairs = flagged.map((c) => `${c.title}:\n- ${c.warnings.join("\n- ")}`).join("\n\n");
    try {
      const repaired = toConcepts(
        await complete(
          completer,
          ctx,
          `Your previous concepts had problems. Rewrite ALL ${concepts.length} concepts, keeping their ideas, but fix these issues (remove unsupported claims, trim dialogue):
${repairs}

Previous concepts (JSON):
${JSON.stringify({ concepts: concepts.map(({ id: _id, warnings: _w, ...c }) => c) })}`,
          CONCEPTS_SCHEMA as unknown as Record<string, unknown>,
          8000,
        ),
        ctx,
      );
      const before = concepts.reduce((n, c) => n + c.warnings.length, 0);
      const after = repaired.reduce((n, c) => n + c.warnings.length, 0);
      if (repaired.length >= concepts.length && after < before) concepts = repaired;
    } catch (error) {
      log.warn("ugc.concepts.repair_failed", {
        message: error instanceof Error ? error.message : String(error),
      });
    }
  }
  return concepts;
}

export async function rewriteScript(
  ctx: ConceptContext,
  script: Script,
  instruction: string,
  completer: Completer = llmText,
): Promise<{ script: Script; warnings: string[] }> {
  const raw = await complete(
    completer,
    ctx,
    `Rewrite this script for a ${ctx.durationSec}-second clip. Instruction from the marketer: "${instruction.slice(0, 300)}"
Keep what works, apply the instruction, and keep every rule above.

Current script (JSON):
${JSON.stringify(script)}`,
    SCRIPT_SCHEMA as unknown as Record<string, unknown>,
    3000,
  );
  const next = normalizeScript(raw as RawScript, ctx);
  if (!next) throw new HttpError(502, "The rewrite couldn't be read. Please try again.");
  return { script: next, warnings: scriptWarnings(next, ctx) };
}
