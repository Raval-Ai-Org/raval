// build-briefs.mjs — distils evals/creative/briefs/g*.json into the server-only
// table of "why it sells" lines (ADR-0053). Only `mechanism` ships; the briefs
// themselves stay study and benchmark data.
//   node scripts/briefs/build-briefs.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = "evals/creative/briefs";
const rows = readdirSync(dir)
  .filter((f) => /^g\d+\.json$/.test(f))
  .sort()
  .flatMap((f) => JSON.parse(readFileSync(path.join(dir, f), "utf8")))
  .map((b) => ({
    id: b.id,
    sector: b.sector,
    goal: b.goal,
    format: b.format,
    mechanism: b.mechanism.trim(),
  }))
  .sort((a, b) => a.id.localeCompare(b.id));

const out = `// GENERATED by scripts/briefs/build-briefs.mjs from evals/creative/briefs. Never hand-edit.
import "server-only";

export type MechanismRow = { id: string; sector: string; goal: string; format: string; mechanism: string };

export const MECHANISMS: readonly MechanismRow[] = ${JSON.stringify(rows, null, 1)};
`;
writeFileSync("src/server/studio/example-briefs.generated.ts", out);
console.log(`${rows.length} mechanism lines written`);
