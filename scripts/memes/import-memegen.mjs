#!/usr/bin/env node
// Imports the curated meme templates into Mellox (Round 5, ADR-0047).
//
//   node scripts/memes/import-memegen.mjs <memegen templates dir> <meme-templates.json>
//
// Reads the annotated catalogue (mechanic, use/avoid, marketing fit, text boxes)
// written during research, keeps the templates fit for brand marketing
// (marketingFit >= 2, not sensitive, not animated), copies each picture into
// public/memes/<id>.jpg (at most 900px wide, re-encoded) and rewrites
// src/lib/studio/memes/templates.generated.ts. Never hand-edit that file.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import sharp from "sharp";

const [templatesDir, catalogPath] = process.argv.slice(2);
if (!templatesDir || !catalogPath) {
  console.error("usage: import-memegen.mjs <memegen templates dir> <meme-templates.json>");
  process.exit(1);
}
const root = resolve(import.meta.dirname, "..", "..");
const outDir = join(root, "public", "memes");
mkdirSync(outDir, { recursive: true });

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const keep = catalog.filter((t) => t.marketingFit >= 2 && !t.sensitive && !t.animated);

const round = (n) => Math.round(Number(n) * 1000) / 1000;
const out = [];
for (const t of keep) {
  const src = join(templatesDir, t.id, t.image ?? "default.jpg");
  if (!existsSync(src)) {
    console.warn("missing picture", t.id);
    continue;
  }
  const pic = sharp(src, { failOn: "none" }).rotate();
  const meta = await pic.metadata();
  const width = Math.min(meta.width ?? t.width ?? 800, 900);
  const buf = await pic
    .resize({ width, withoutEnlargement: true })
    .flatten({ background: "#ffffff" })
    .jpeg({ quality: 84, mozjpeg: true })
    .toBuffer();
  const size = await sharp(buf).metadata();
  writeFileSync(join(outDir, `${t.id}.jpg`), buf);
  const boxes = (t.boxes ?? []).map((b) => {
    const box = [
      round(b.anchor_x ?? 0),
      round(b.anchor_y ?? 0),
      round(b.scale_x ?? 1),
      round(b.scale_y ?? 0.2),
    ];
    const extra = {};
    if (b.align && b.align !== "center") extra.align = b.align;
    if (b.color && b.color !== "white") extra.color = b.color;
    if (b.style && b.style !== "upper") extra.style = b.style;
    return Object.keys(extra).length ? [...box, extra] : box;
  });
  if (!boxes.length) continue;
  out.push({
    id: t.id,
    name: t.name,
    mechanic: t.mechanic,
    use: t.useWhen,
    avoid: t.avoidWhen,
    fit: t.marketingFit,
    ...(t.realPerson ? { person: true } : {}),
    w: size.width,
    h: size.height,
    boxes,
  });
}

const header = `// GENERATED by scripts/memes/import-memegen.mjs from the memegen template
// catalogue (annotated in Round 5). Never hand-edit; re-run the script.
// Each picture is public/memes/<id>.jpg; a box is [x, y, w, h] as fractions of
// the picture (memegen's anchor and scale), optionally with align, colour and
// style ("none" keeps the case as written, otherwise upper case).
import type { MemeTemplate } from "./types";

export const MEME_TEMPLATES: readonly MemeTemplate[] = `;
writeFileSync(
  join(root, "src", "lib", "studio", "memes", "templates.generated.ts"),
  `${header}${JSON.stringify(out, null, 1)} as const satisfies readonly MemeTemplate[];\n`,
);
console.log(`kept ${out.length} of ${catalog.length} templates`);
